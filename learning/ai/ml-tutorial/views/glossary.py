df = pd.DataFrame(TERMS, columns=["英文", "中文", "分類", "白話解釋"])

c1, c2 = st.columns([2, 3])
with c1:
    cats = st.multiselect("篩選分類", sorted(df["分類"].unique()), default=[])
with c2:
    q = st.text_input("🔍 搜尋（中英文都可以）", "")

view = df.copy()
if cats:
    view = view[view["分類"].isin(cats)]
if q:
    mask = view.apply(lambda r: q.lower() in " ".join(r.astype(str)).lower(), axis=1)
    view = view[mask]

st.caption(f"共 {len(view)} 個名詞")
st.dataframe(view, width="stretch", hide_index=True, height=620)
