with tabs[2]:
    st.markdown("### 機器學習")

    interview(
        "決策樹怎麼決定要問哪個問題？",
        """
**目標：找出讓分完之後「兩邊最純」的那個切分點。**

「純」的衡量方式有兩種：

- **Gini 不純度**：`1 − Σpᵢ²`。全部同一類時是 0（最純）。**sklearn 預設**，算得快。
- **資訊熵 Entropy**：`−Σpᵢ log pᵢ`。用它時，減少的量叫 **Information Gain**。

**流程**：對每個特徵的每個可能切分點，算「分完之後的加權不純度」，
挑下降最多的那個。然後在左右兩邊遞迴重複。

**什麼時候停**：達到 `max_depth`、節點樣本數少於 `min_samples_split`、
或已經完全純了。**不設停止條件的話一定會過擬合**（每個葉子一個樣本）。
""",
    )

    interview(
        "XGBoost 為什麼那麼強？",
        """
**四個原因**：

1. **Boosting 的本質**：每棵新樹專門去修正前面所有樹的**殘差**，
   等於不斷針對錯題加強，逼近能力很強。
2. **內建正則化**：目標函數裡直接加了樹複雜度的懲罰項（葉子數、葉子權重的 L2），
   這是它比傳統 GBDT 強的關鍵。
3. **二階導數**：用泰勒展開到二階（Hessian），
   比只用一階梯度的方法收斂更快更準。
4. **工程優化**：支援平行化找切分點、缺值自動處理、
   直方圖近似演算法（LightGBM 更進一步）。

**什麼時候不該用**：
- 資料是**影像/文字/音訊** → 用深度學習
- 資料量**極小**（幾百筆）→ 容易過擬合，用簡單模型
- 需要**極高可解釋性**（金融審核、醫療）→ 用單棵決策樹或邏輯迴歸
""",
    )

    interview(
        "K-Means 怎麼決定 K 要設多少？",
        """
**三種方法，實務上要合併使用**：

1. **手肘法 Elbow Method**
   畫「K vs 群內平方和 (WCSS)」，找曲線的轉折點。
   ⚠️ 缺點：轉折點常常很模糊，主觀性強。

2. **輪廓係數 Silhouette Score**
   衡量「同群內多緊密、跟其他群多分離」，範圍 −1～1，**越大越好**。
   比手肘法客觀。

3. **業務需求**（**最重要，但最多人忘記講**）
   行銷部門只有預算做 4 種不同的活動，那 K 就是 4。
   分出 20 群數學上最佳，但沒人有能力執行，等於沒用。

**加分句**：K-Means 假設群是**球形且大小相近**，
遇到不規則形狀的群要改用 **DBSCAN**（還能自動找出離群點）
或 **GMM**（高斯混合模型，允許橢圓形）。
""",
    )

    interview(
        "特徵重要性（feature importance）可以直接拿來解釋因果嗎？",
        """
**不行。** 這題答對加分很多。

**兩個問題**：

1. **它反映的是「模型用了什麼」，不是「真實世界的因果」。**
   如果兩個特徵高度相關，模型可能隨機挑一個用，
   另一個重要性就變 0 —— 但它其實一樣重要。

2. **樹模型的預設 importance（基於不純度下降）有偏誤**：
   會**高估高基數特徵**（例如 ID、郵遞區號這種取值很多的欄位）。

**比較可靠的替代方案**：
- **Permutation Importance**：把某欄打亂，看分數掉多少。直觀且不易被騙。
- **SHAP values**：基於博弈論，可以看**單筆預測**是被哪些特徵推高推低。
  現在是業界標準，面試講得出 SHAP 是加分項。

**但仍要強調**：這些都只是**關聯性**的解釋，要談因果得做實驗。
""",
    )

