with tabs[3]:
    st.markdown("### 深度學習")

    interview(
        "Batch Normalization 在做什麼？為什麼有用？",
        """
**做什麼**：把每一層的輸出，在 batch 這個維度上標準化成平均 0、變異數 1，
再乘上兩個**可學習的參數** γ 和 β（讓模型有能力還原原本的分布）。

**為什麼有用**（原論文說是減少 Internal Covariate Shift，但後來被質疑）：
現在比較被接受的解釋是**它讓損失函數的地形變平滑**，
所以可以用**更大的學習率**，收斂更快、也比較不會卡在爛的局部解。

**副作用**：因為統計量是從 batch 算的，帶有隨機性，有**輕微正則化效果**。

**三個實務重點**：
1. **訓練和推論的行為不同**：訓練用當下 batch 的統計量，
   推論用訓練時累積的移動平均 → 所以一定要記得 `model.eval()`
2. **batch size 太小時效果很差**（統計量不準）→ 改用 **LayerNorm** 或 GroupNorm
3. **Transformer 用 LayerNorm 不用 BatchNorm**，
   因為序列長度不固定，且 NLP 的 batch 統計量不穩定
""",
    )

    interview(
        "Adam 優化器和 SGD 的差別？",
        """
| | **SGD (+ Momentum)** | **Adam** |
|---|---|---|
| 學習率 | 所有參數共用一個 | **每個參數各自調整** |
| 原理 | 沿梯度方向走，動量幫忙衝過小坑 | 動量 + 依梯度歷史大小自適應調整步伐 |
| 收斂速度 | 慢 | **快** |
| 最終效果 | **常常更好**（泛化能力較佳） | 有時略差 |
| 調參難度 | 學習率很難調 | **不太需要調，1e-3 通常就能用** |

**實務**：
- 起手式一律 **Adam(lr=1e-3)**，先讓模型跑起來
- 影像分類要衝 SOTA，很多論文用 **SGD + Momentum + 學習率排程**
- **AdamW**（把 weight decay 從梯度裡分離出來）是現在訓練 Transformer 的標配

**加分句**：學習率排程（warmup + cosine decay）的影響往往比選哪個 optimizer 更大。
""",
    )

    interview(
        "什麼是遷移學習？什麼時候該凍結多少層？",
        """
**遷移學習**：拿在大資料集（ImageNet）上訓練好的模型，
換掉最後的分類層，用自己的少量資料微調。

**因為**：前幾層學到的是「邊緣、紋理、顏色」等**通用特徵**，
任何影像任務都用得到，不需要重學。

**該凍結多少層，看兩個維度**：

| | **你的資料量小** | **你的資料量大** |
|---|---|---|
| **和原資料相似**（例如都是自然照片） | 凍結全部，**只訓練最後一層** | 微調**後面幾層** |
| **和原資料差很多**（例如醫學影像、衛星圖） | 凍結前面，訓練**後面幾層**（資料太少只能這樣） | **全部解凍微調**，或乾脆從零訓練 |

**實務技巧**：解凍時**學習率要調小 10 倍**（例如 1e-4），
否則會把預訓練學到的好權重直接沖掉，這叫 **catastrophic forgetting**。
""",
    )

    interview(
        "怎麼判斷該用機器學習還是深度學習？",
        """
**決策樹（雙關）**：

**先問資料型態**
- **表格資料**（Excel 那種）→ **XGBoost / LightGBM**。
  深度學習在表格資料上長期輸給樹模型，這是有大量論文證實的。
- **影像 / 文字 / 音訊 / 影片** → **深度學習**，而且直接用預訓練模型微調。

**再問資料量**
- < 1 萬筆 → 傳統 ML（深度學習會過擬合）
- 1 萬～10 萬 → 都可以，先試傳統 ML 當 baseline
- \\> 10 萬 → 深度學習開始有優勢

**最後問限制**
- 需要**解釋每一筆預測的理由**（金融、醫療法規）→ 傳統 ML
- 只有 CPU、要毫秒級回應 → 傳統 ML
- 有 GPU、可以離線批次跑 → 深度學習

**加分句**：不管哪種，我都會**先跑一個簡單的 baseline**。
沒有 baseline，就不知道複雜模型到底有沒有真的比較好。
""",
    )

