        "<b>轉職者被刷掉，技術原因反而是少數。</b>最常見的是：<br>"
        "① 講不出「為什麼要轉」的可信理由<br>"
        "② 專案只會講技術，講不出商業價值<br>"
        "③ 讓面試官覺得「他只是想換工作，不是真的想做這個」"
